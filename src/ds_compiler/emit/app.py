"""Write the compiled Django app package.

Layout produced under ``--out``::

    overrides-report.json
    <app>/__init__.py
    <app>/apps.py
    <app>/runtime.py               (copied verbatim from the compiler)
    <app>/spec.py                  (generated prop/slot metadata)
    <app>/templatetags/ds.py       (generated tag registrations)
    <app>/templates/ds/*.html      (generated partials)
    <app>/static/ds/tokens.css
    <app>/static/ds/components.css
"""

from __future__ import annotations

import json
import pprint
import shutil
from pathlib import Path

from ..model import ValidatedSpec
from ..runtime import runtime_source
from .css import render_components_css, render_tokens_css
from .templates import render_template

PY_HEADER = '"""GENERATED by ds-compile - do not edit. Edit the spec and recompile."""'


def _write(path: Path, content: str, written: list[Path]) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(content, encoding="utf-8")
    written.append(path)


def render_spec_module(spec: ValidatedSpec) -> str:
    components = {component.name: component.as_data() for component in spec.components}
    tokens = {token.ref: token.css_var for token in spec.tokens}
    body = [
        PY_HEADER,
        "",
        "# Component metadata, straight from the design spec. The template tag layer",
        "# validates props against this at parse and render time.",
        "COMPONENTS = " + pprint.pformat(components, indent=1, width=100, sort_dicts=False),
        "",
        "# Token reference -> CSS custom property, for tooling and debugging.",
        "TOKEN_VARS = " + pprint.pformat(tokens, indent=1, width=100, sort_dicts=False),
        "",
    ]
    return "\n".join(body)


def render_templatetags_module(spec: ValidatedSpec) -> str:
    lines = [
        PY_HEADER,
        "",
        "from django import template",
        "",
        "from ..runtime import parse_component, parse_slot",
        "",
        "register = template.Library()",
        "",
        '# {% ds_slot "name" %}...{% end_ds_slot %} fills a named slot of the enclosing component.',
        'register.tag("ds_slot", parse_slot)',
        "",
    ]
    for component in spec.components:
        usage = f"{{% {component.tag_name} %}}"
        if component.block:
            usage = f"{{% {component.tag_name} %}}...{{% end_{component.tag_name} %}}"
        lines.extend(
            [
                "",
                f'@register.tag("{component.tag_name}")',
                f"def {component.tag_name}(parser, token):",
                f'    """{component.name} ({component.level}) - {usage}',
                "",
                f"    props: {', '.join(component.props) or 'none'}",
                f"    slots: {', '.join(component.slots) or 'none'}",
                '    """',
                f'    return parse_component(parser, token, "{component.name}")',
            ]
        )
    return "\n".join(lines) + "\n"


def render_apps_module(app_name: str) -> str:
    return "\n".join(
        [
            PY_HEADER,
            "",
            "from django.apps import AppConfig",
            "",
            "",
            "class DesignSystemConfig(AppConfig):",
            f'    name = "{app_name}"',
            '    label = "ds"',
            '    verbose_name = "Design system (generated)"',
            "",
        ]
    )


def render_overrides_report(spec: ValidatedSpec) -> str:
    overrides = spec.overrides
    report = {
        "$description": (
            "Every use of the design system's single escape hatch. Each entry is a gap in the "
            "spec vocabulary: promote recurring ones into tokens/components, then delete the override."
        ),
        "count": len(overrides),
        "components_with_overrides": sorted({override.component for override in overrides}),
        "overrides": [override.as_data() for override in overrides],
    }
    return json.dumps(report, indent=2, ensure_ascii=False) + "\n"


def write_app(spec: ValidatedSpec, out_dir: Path, app_name: str = "ds", clean: bool = True) -> list[Path]:
    """Emit the whole app. Returns the list of written files."""
    out_dir = Path(out_dir)
    app_dir = out_dir / app_name
    if clean and app_dir.exists():
        shutil.rmtree(app_dir)
    written: list[Path] = []
    by_name = spec.by_name

    _write(
        app_dir / "__init__.py",
        "\n".join(
            [
                '"""GENERATED design system Django app - do not edit.',
                "",
                f'Add "{app_name}.apps.DesignSystemConfig" to INSTALLED_APPS, then',
                "{% load ds %} in your templates.",
                '"""',
                "",
            ]
        ),
        written,
    )
    _write(app_dir / "apps.py", render_apps_module(app_name), written)
    _write(app_dir / "runtime.py", runtime_source(), written)
    _write(app_dir / "spec.py", render_spec_module(spec), written)
    _write(app_dir / "templatetags" / "__init__.py", "", written)
    _write(app_dir / "templatetags" / "ds.py", render_templatetags_module(spec), written)

    for component in spec.components:
        _write(app_dir / "templates" / component.template_name, render_template(component, by_name), written)

    _write(app_dir / "static" / "ds" / "tokens.css", render_tokens_css(spec.tokens), written)
    _write(app_dir / "static" / "ds" / "components.css", render_components_css(spec), written)

    _write(out_dir / "overrides-report.json", render_overrides_report(spec), written)
    return written
