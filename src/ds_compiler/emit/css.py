"""CSS emission.

Tokens become custom properties on ``:root``; aliases stay aliases (``var(--x)``),
so the token graph survives into the stylesheet. Component styles only ever emit
``var(--ds-...)`` references - the compiler has already proven there are no
literals outside token files and ``override`` nodes.
"""

from __future__ import annotations

import re
from typing import Any

from ..model import Component, ValidatedSpec
from ..tokens import ALIAS_RE, TokenSet
from ..validate import override_class

HEADER = "/* GENERATED by ds-compile - do not edit. Edit the spec and recompile. */"
_SAFE_FONT_NAME = re.compile(r"^[A-Za-z][A-Za-z0-9-]*$")


def _format_number(value: int | float) -> str:
    return f"{value:g}"


def _format_font_family(value: list[Any]) -> str:
    parts = []
    for item in value:
        text = str(item)
        parts.append(text if _SAFE_FONT_NAME.match(text) else f'"{text}"')
    return ", ".join(parts)


def token_value_css(tokens: TokenSet, ref: str) -> str:
    """The CSS text for a token's own declaration (alias -> var(), literal -> literal)."""
    token = tokens.get(ref)
    assert token is not None  # guaranteed by validation
    if token.alias is not None:
        target = tokens.get(token.alias)
        assert target is not None
        return f"var({target.css_var})"
    value = token.value
    if isinstance(value, list):
        return _format_font_family(value)
    if isinstance(value, bool):  # pragma: no cover - not a valid token value
        return str(value)
    if isinstance(value, (int, float)):
        return _format_number(value)
    return str(value)


def style_value_css(tokens: TokenSet, value: Any) -> str:
    """The CSS text for a component style value (token references -> var())."""
    items = value if isinstance(value, list) else [value]
    out = []
    for item in items:
        match = ALIAS_RE.match(item)
        if match:
            token = tokens.get(match.group(1))
            assert token is not None  # guaranteed by validation
            out.append(f"var({token.css_var})")
        else:
            out.append(item)
    return " ".join(out)


def render_tokens_css(tokens: TokenSet) -> str:
    lines = [HEADER, "", ":root {"]
    current_source: str | None = None
    for token in tokens:
        if token.source != current_source:
            if current_source is not None:
                lines.append("")
            lines.append(f"  /* {token.source} */")
            current_source = token.source
        lines.append(f"  {token.css_var}: {token_value_css(tokens, token.ref)};")
    lines.append("}")
    return "\n".join(lines) + "\n"


def _selector(component: Component, part: str | None, modifier: str | None, state: str | None) -> str:
    if modifier:
        modifier_class = f".{component.modifier_class(modifier)}"
        selector = modifier_class if not part else f"{modifier_class} .{component.part_class(part)}"
    else:
        selector = f".{component.part_class(part)}"
    if state:
        selector += f":{state}"
    return selector


def _rule(selector: str, declarations: list[tuple[str, str]]) -> list[str]:
    lines = [f"{selector} {{"]
    lines.extend(f"  {name}: {value};" for name, value in declarations)
    lines.append("}")
    return lines


def _declarations(tokens: TokenSet, styles: dict[str, Any]) -> list[tuple[str, str]]:
    return [(name, style_value_css(tokens, value)) for name, value in styles.items()]


def render_component_css(component: Component, tokens: TokenSet) -> str:
    blocks: list[list[str]] = []
    override_blocks: list[list[str]] = []

    for _path, node in component.nodes():
        kind = node.get("node")
        if kind == "element":
            part = node.get("part")
            styles = node.get("styles") or {}
            if styles:
                blocks.append(_rule(_selector(component, part, None, None), _declarations(tokens, styles)))
            for state, body in (node.get("states") or {}).items():
                blocks.append(
                    _rule(_selector(component, part, None, state), _declarations(tokens, body.get("styles") or {}))
                )
            for modifier in node.get("modifiers") or []:
                name = modifier.get("class") or str(modifier["value"]).lower()
                if modifier.get("styles"):
                    blocks.append(
                        _rule(_selector(component, part, name, None), _declarations(tokens, modifier["styles"]))
                    )
                for state, body in (modifier.get("states") or {}).items():
                    blocks.append(
                        _rule(
                            _selector(component, part, name, state),
                            _declarations(tokens, body.get("styles") or {}),
                        )
                    )
        elif kind == "override":
            declarations = list((node.get("css") or {}).items())
            if not declarations:
                continue
            override_blocks.append(
                [
                    f"/* OVERRIDE {node['id']} - {node['reason']} */",
                    *_rule(f".{override_class(node['id'])}", declarations),
                ]
            )

    header = [
        "/* " + "-" * 68,
        f"   {component.name} ({component.level}) - {component.source}",
        "   " + "-" * 68 + " */",
    ]
    out = header + [line for block in blocks + override_blocks for line in block + [""]]
    return "\n".join(out)


def render_components_css(spec: ValidatedSpec) -> str:
    parts = [HEADER, ""]
    for component in spec.components:
        parts.append(render_component_css(component, spec.tokens))
    return "\n".join(parts).rstrip() + "\n"
