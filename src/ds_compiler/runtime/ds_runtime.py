"""Runtime support for the generated design-system Django app.

Copied verbatim by ds-compile. Do not edit this file in the compiled output -
edit ``src/ds_compiler/runtime/ds_runtime.py`` in the compiler and recompile.

Responsibilities:

* validate props at render time against the spec-declared types and enums
* collect ``{% ds_slot "name" %}`` content for container components
* render the generated partial template for a component
"""

from __future__ import annotations

from typing import Any

from django.template import Node, TemplateSyntaxError
from django.template.base import token_kwargs
from django.utils.safestring import mark_safe

from .spec import COMPONENTS

SLOT_FRAMES = "_ds_slot_frames"
_MISSING = object()


class DsPropError(TemplateSyntaxError):
    """A component was used with props the spec does not declare or allow."""


class DsSlotError(TemplateSyntaxError):
    """Slot content was provided for a slot the spec does not declare."""


class SlotFrame:
    """Collects slot content while a component's block body is rendered."""

    __slots__ = ("component", "allowed", "content")

    def __init__(self, component: str, allowed: tuple[str, ...]) -> None:
        self.component = component
        self.allowed = allowed
        self.content: dict[str, Any] = {}


def _describe(prop: dict) -> str:
    if prop["type"] == "enum":
        return f"one of {prop['values']}"
    return f"a {prop['type']}"


def coerce_prop(component: str, name: str, prop: dict, value: Any) -> Any:
    """Validate/normalise one prop value. Raises :class:`DsPropError`."""
    kind = prop["type"]
    if value is None:
        if prop.get("required"):
            raise DsPropError(f"ds_{component}: required prop '{name}' must not be None")
        return None
    if kind == "enum":
        if value in prop["values"]:
            return value
        raise DsPropError(
            f"ds_{component}: prop '{name}' must be {_describe(prop)}, got {value!r}"
        )
    if kind == "boolean":
        if isinstance(value, bool):
            return value
        if value in (0, 1):
            return bool(value)
        if isinstance(value, str) and value.lower() in ("true", "false", ""):
            return value.lower() == "true"
        raise DsPropError(f"ds_{component}: prop '{name}' must be a boolean, got {value!r}")
    if kind == "number":
        if isinstance(value, bool):
            raise DsPropError(f"ds_{component}: prop '{name}' must be a number, got {value!r}")
        if isinstance(value, (int, float)):
            return value
        try:
            return float(value)
        except (TypeError, ValueError):
            raise DsPropError(f"ds_{component}: prop '{name}' must be a number, got {value!r}") from None
    # string
    if isinstance(value, str):
        if prop.get("required") and not value:
            raise DsPropError(f"ds_{component}: required prop '{name}' must not be empty")
        return value
    return str(value)


def validate_props(component: str, values: dict[str, Any]) -> dict[str, Any]:
    """Check ``values`` against the spec and fill in declared defaults."""
    declared = COMPONENTS[component]["props"]
    resolved: dict[str, Any] = {}
    for name, value in values.items():
        prop = declared.get(name)
        if prop is None:
            raise DsPropError(
                f"ds_{component}: unknown prop '{name}'. Declared props: "
                f"{sorted(declared) or 'none'}"
            )
        resolved[name] = coerce_prop(component, name, prop, value)
    for name, prop in declared.items():
        if name in resolved:
            continue
        if prop.get("required"):
            raise DsPropError(f"ds_{component}: required prop '{name}' is missing")
        resolved[name] = prop.get("default")
    return resolved


def _static_value(expression) -> Any:
    """The literal value of a template expression, or ``_MISSING`` if it is dynamic."""
    if expression.filters:
        return _MISSING
    var = expression.var
    if isinstance(var, str):
        return var
    literal = getattr(var, "literal", None)
    return _MISSING if literal is None else literal


def _frames(context) -> list[SlotFrame]:
    render_context = context.render_context
    frames = render_context.get(SLOT_FRAMES)
    if frames is None:
        frames = []
        render_context[SLOT_FRAMES] = frames
    return frames


class ComponentNode(Node):
    """Renders one design system component."""

    def __init__(self, component: str, kwargs: dict, nodelist=None) -> None:
        self.component = component
        self.kwargs = kwargs
        self.nodelist = nodelist

    def __repr__(self) -> str:  # pragma: no cover - debugging aid
        return f"<ComponentNode: {self.component}>"

    def render(self, context) -> str:
        meta = COMPONENTS[self.component]
        values = {name: expression.resolve(context) for name, expression in self.kwargs.items()}
        props = validate_props(self.component, values)

        slots: dict[str, Any] = {}
        if self.nodelist is not None:
            frame = SlotFrame(self.component, tuple(meta["slots"]))
            frames = _frames(context)
            frames.append(frame)
            try:
                body = self.nodelist.render(context)
            finally:
                frames.pop()
            slots = dict(frame.content)
            if body.strip() and "default" not in slots:
                if "default" not in frame.allowed:
                    raise DsSlotError(
                        f"ds_{self.component}: stray content in block body; '{self.component}' has no "
                        f"'default' slot. Wrap content in one of {list(frame.allowed)} using "
                        '{% ds_slot "name" %}'
                    )
                slots["default"] = mark_safe(body)

        props["slots"] = slots
        template = context.template.engine.get_template(meta["template"])
        return template.render(context.new(props))


class SlotNode(Node):
    """Captures block content for one named slot of the enclosing component."""

    def __init__(self, name: str, nodelist) -> None:
        self.name = name
        self.nodelist = nodelist

    def __repr__(self) -> str:  # pragma: no cover - debugging aid
        return f"<SlotNode: {self.name}>"

    def render(self, context) -> str:
        frames = _frames(context)
        if not frames:
            raise DsSlotError(
                '{% ds_slot "'
                + self.name
                + '" %} must appear inside a design system component block tag'
            )
        frame = frames[-1]
        if self.name not in frame.allowed:
            raise DsSlotError(
                f"ds_{frame.component} has no slot '{self.name}' (declared: {list(frame.allowed)})"
            )
        if self.name in frame.content:
            raise DsSlotError(f"ds_{frame.component}: slot '{self.name}' is filled more than once")
        frame.content[self.name] = mark_safe(self.nodelist.render(context))
        return ""


def parse_component(parser, token, component: str):
    """Shared parser for every generated ``{% ds_<name> %}`` tag."""
    meta = COMPONENTS[component]
    declared = meta["props"]
    bits = token.split_contents()
    tag_name, rest = bits[0], bits[1:]
    kwargs = token_kwargs(rest, parser, support_legacy=False)
    if rest:
        raise DsPropError(
            f"{{% {tag_name} %}} takes keyword arguments only; got {' '.join(rest)!r}"
        )
    for name, expression in kwargs.items():
        if name not in declared:
            raise DsPropError(
                f"{{% {tag_name} %}}: unknown prop '{name}'. Declared props: "
                f"{sorted(declared) or 'none'}"
            )
        static = _static_value(expression)
        if static is not _MISSING:
            coerce_prop(component, name, declared[name], static)
    for name, prop in declared.items():
        if prop.get("required") and name not in kwargs:
            raise DsPropError(f"{{% {tag_name} %}}: required prop '{name}' is missing")

    nodelist = None
    if meta["block"]:
        end_tag = f"end_{tag_name}"
        nodelist = parser.parse((end_tag,))
        parser.delete_first_token()
    return ComponentNode(component, kwargs, nodelist)


def parse_slot(parser, token):
    """``{% ds_slot "name" %}...{% end_ds_slot %}``"""
    bits = token.split_contents()
    if len(bits) != 2:
        raise DsSlotError('{% ds_slot %} takes exactly one argument: the slot name, quoted.')
    raw = bits[1]
    if not (len(raw) > 2 and raw[0] == raw[-1] and raw[0] in "\"'"):
        raise DsSlotError("{% ds_slot %} name must be a quoted literal, got " + raw)
    nodelist = parser.parse(("end_ds_slot",))
    parser.delete_first_token()
    return SlotNode(raw[1:-1], nodelist)
